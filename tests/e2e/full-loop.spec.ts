import { test, expect, startLesson, answerCheck, askGuide, submitActivity, activity, water, events, expectTopicMetrics } from "./fixtures";
test("full loop: curious learner, cited guide, observe activity, next step and topic session metrics",async({page})=>{
  await startLesson(page);await answerCheck(page);
  await askGuide(page,"Why does the dry season matter?","wa-03");
  await page.getByRole("region",{name:"Ask the learning guide",exact:true}).getByRole("link",{name:/^wa-03/}).click();
  await expect(page).toHaveURL(/#wa-03$/);
  await page.getByRole("link",{name:"Try the activity",exact:true}).click();
  await submitActivity(page,"observe",activity.paths.find(path=>path.id==="observe")!.example!);
  await expect(page.getByRole("heading",{name:"Activity completed",exact:true})).toBeVisible();
  await page.getByRole("link",{name:"See my next steps",exact:true}).click();
  await expect(page).toHaveURL(`${water.url}/next`);
  await expect(page.getByRole("heading",{name:"Recommended next step",exact:true})).toBeVisible();
  await page.getByRole("radio",{name:"Yes",exact:true}).check();
  const session=page.locator('[aria-labelledby="session-title"]');
  await expect(session.getByText("Completed activity: Yes",{exact:true})).toBeVisible();
  await expect(session.getByText("Check score: 3/3",{exact:true})).toBeVisible();
  await expect(session.getByText("Would return: yes",{exact:true})).toBeVisible();
  const log=await events(page);
  expect(log.filter(event=>!event.name.startsWith("lab_")).map(event=>event.name)).toEqual(["intention_chosen","area_opened","subject_opened","topic_opened","lesson_viewed","check_answered","check_answered","check_answered","guide_asked","activity_submitted","activity_completed","would_return"]);
  expect(log.some(event=>event.name==="lab_started" && event.details.topicId===water.meta.id)).toBe(true);
  expect(log.filter(event=>event.name==="check_answered").every(event=>event.details.correct)).toBe(true);
  await expectTopicMetrics(page);
});
