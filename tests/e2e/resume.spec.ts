import { test, expect, startLesson, submitActivity, fictionalAnswer, water, catalog, events } from "./fixtures";
test("resume: answers, draft, feedback, preferences and topic events survive reload; start over clears session",async({page})=>{
  await startLesson(page);
  const check=water.config.understandingCheck[0];
  const answer=page.getByRole("group",{name:check.question,exact:true}).getByRole("radio").nth(check.answerIndex);
  await answer.check();await page.reload();await expect(answer).toBeChecked();
  await page.getByRole("link",{name:"Try the activity",exact:true}).click();
  await page.getByRole("radio",{name:water.activity.paths.find(path=>path.id==="fictional")!.label,exact:true}).check();
  await page.getByLabel("Your answer",{exact:true}).fill(fictionalAnswer);
  await page.reload();await expect(page.getByLabel("Your answer",{exact:true})).toHaveValue(fictionalAnswer);
  await page.locator("header").getByRole("link",{name:catalog.product.name,exact:true}).click();
  await expect(page.getByRole("link",{name:"Continue where you left off",exact:true})).toHaveAttribute("href",`${water.url}/activity`);
  await page.getByRole("link",{name:"Continue where you left off",exact:true}).click();
  await submitActivity(page,"fictional",fictionalAnswer);
  await page.reload();await expect(page.getByRole("heading",{name:"Activity completed",exact:true})).toBeVisible();
  await page.getByRole("link",{name:"See my next steps",exact:true}).click();
  await page.getByRole("checkbox").check();await page.getByRole("radio",{name:"Maybe",exact:true}).check();
  const before=await events(page);await page.reload();
  await expect(page.getByRole("checkbox")).toBeChecked();await expect(page.getByRole("radio",{name:"Maybe",exact:true})).toBeChecked();
  await expect(page.getByText("Would return: maybe",{exact:true})).toBeVisible();expect(await events(page)).toEqual(before);
  await page.locator("header").getByRole("link",{name:catalog.product.name,exact:true}).click();
  await expect(page.getByRole("link",{name:"Continue where you left off",exact:true})).toHaveAttribute("href",`${water.url}/next`);
  await page.getByRole("link",{name:"Continue where you left off",exact:true}).click();
  await page.getByRole("link",{name:"Start over",exact:true}).click();
  await expect(page.getByRole("link",{name:"Continue where you left off",exact:true})).toHaveCount(0);
  expect(await events(page)).toEqual([]);
  expect(await page.evaluate(()=>localStorage.getItem("agri-progress-v2"))).toBeNull();
});
