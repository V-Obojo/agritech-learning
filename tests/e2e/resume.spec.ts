import { test, expect, startLesson, submitActivity, fictionalAnswer, events } from "./fixtures";
test("resume: answers, draft, feedback, preferences and events survive reload; start over clears session", async ({ page }) => {
  await startLesson(page);
  await page.getByRole("radio").nth(1).check();
  await page.reload();
  await expect(page.getByRole("radio").nth(1)).toBeChecked();
  await page.getByRole("link", { name: "Try the activity", exact: true }).click();
  await page.getByLabel("Your answer", { exact: true }).fill(fictionalAnswer);
  await page.reload();
  await expect(page.getByLabel("Your answer", { exact: true })).toHaveValue(fictionalAnswer);
  await page.getByRole("link", { name: "Fish Farming Basics", exact: true }).click();
  await expect(page.getByRole("link", { name: "Continue where you left off", exact: true })).toHaveAttribute("href", "/activity");
  await page.getByRole("link", { name: "Continue where you left off", exact: true }).click();
  await submitActivity(page, "fictional", fictionalAnswer);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Activity completed", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "See my next steps", exact: true }).click();
  await page.getByRole("checkbox").check();
  await page.getByRole("radio", { name: "Maybe", exact: true }).check();
  const before = await events(page);
  await page.reload();
  await expect(page.getByRole("checkbox")).toBeChecked();
  await expect(page.getByRole("radio", { name: "Maybe", exact: true })).toBeChecked();
  await expect(page.getByText("Would return: maybe", { exact: true })).toBeVisible();
  expect(await events(page)).toEqual(before);
  await page.getByRole("link", { name: "Fish Farming Basics", exact: true }).click();
  await expect(page.getByRole("link", { name: "Continue where you left off", exact: true })).toHaveAttribute("href", "/next");
  await page.getByRole("link", { name: "Continue where you left off", exact: true }).click();
  await page.getByRole("link", { name: "Start over", exact: true }).click();
  await expect(page.getByRole("link", { name: "Continue where you left off", exact: true })).toHaveCount(0);
  expect(await events(page)).toEqual([]);
});
